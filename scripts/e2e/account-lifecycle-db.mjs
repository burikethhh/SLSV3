// Disposable, in-memory PostgreSQL regression test. No cloud connection.
// Install @electric-sql/pglite in a temp folder and set SLS_TEST_DEPENDENCIES
// to that folder (see docs/ACCOUNT-FIRST-IMPLEMENTATION-2026-10-13.md).
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { randomUUID } from "node:crypto";

if (!process.env.SLS_TEST_DEPENDENCIES) throw new Error("Set SLS_TEST_DEPENDENCIES to an isolated PGlite installation");
const { PGlite } = await import(pathToFileURL(join(process.env.SLS_TEST_DEPENDENCIES, "node_modules/@electric-sql/pglite/dist/index.js")).href);
const sql = new PGlite();
let tests = 0;
const pass = (name) => { tests++; console.log(`PASS ${name}`); };
const rejects = async (name, query, params = []) => { await assert.rejects(sql.query(query, params)); pass(name); };
try {
  await sql.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth;
    grant usage on schema public to authenticated,service_role;
    alter default privileges in schema public grant all on tables to authenticated,service_role;
    create table auth.users(id uuid primary key, email text, email_confirmed_at timestamptz, raw_app_meta_data jsonb default '{}');
    create table auth.mfa_factors(id uuid primary key,user_id uuid references auth.users(id),status text);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}') $$;`);
  const folder = resolve(import.meta.dirname, "../../supabase/migrations");
  for (const filename of (await readdir(folder)).filter((name) => name.endsWith(".sql")).sort()) {
    try { await sql.exec(await readFile(join(folder, filename), "utf8")); }
    catch(error) { throw new Error(`${filename}: ${error.message} (position ${error.position ?? "unknown"})`); }
  }
  pass("all migrations apply to disposable PostgreSQL");
  const owner = randomUUID(), gym = randomUUID(), trial = randomUUID(), otherGym = randomUUID();
  await sql.query("insert into auth.users(id,email,email_confirmed_at) values($1,'owner@example.invalid',now())", [owner]);
  const provision = "select provision_owner_trial($1,$2,'Fixture Gym','Test branch','pro',$3,'synthetic-signed-token',now()+interval '14 days') id";
  const first = await sql.query(provision, [owner, gym, trial]);
  assert.equal(first.rows[0].id, gym);
  const second = await sql.query(provision, [owner, randomUUID(), randomUUID()]);
  assert.equal(second.rows[0].id, gym);
  assert.equal((await sql.query("select count(*)::int count from gyms where owner_user_id=$1", [owner])).rows[0].count, 1);
  assert.equal((await sql.query("select count(*)::int count from licenses where gym_id=$1", [gym])).rows[0].count, 1);
  pass("trial retries return original facility and subscription");
  await sql.query("update auth.users set raw_app_meta_data='{}' where id=$1", [owner]);
  await sql.query(provision, [owner, randomUUID(), randomUUID()]);
  assert.equal((await sql.query("select raw_app_meta_data->>'role' role from auth.users where id=$1", [owner])).rows[0].role, "owner");
  assert.equal((await sql.query("select count(*)::int count from licenses where gym_id=$1", [gym])).rows[0].count, 1);
  pass("historical account repair does not reset or duplicate the trial");
  const unverified = randomUUID();
  await sql.query("insert into auth.users(id,email) values($1,'unverified@example.invalid')", [unverified]);
  await rejects("unverified account cannot start trial", provision, [unverified, randomUUID(), randomUUID()]);
  const paid = "select activate_paid_subscription($1,$2,$3,'synthetic-paid-token','pro',now()+interval '30 days',199,'CEO fixture','receipt-fixture')";
  await rejects("pending facility cannot activate paid subscription", paid, [gym, trial, randomUUID()]);
  await sql.query("update gyms set status='active' where id=$1", [gym]);
  assert.equal((await sql.query("select count(*)::int count from licenses where gym_id=$1", [gym])).rows[0].count, 1);
  pass("approval alone does not issue paid subscription");
  assert.equal(Number((await sql.query("select mrr_usd from fleet_mrr")).rows[0].mrr_usd), 0);
  pass("trial does not count as paid monthly revenue");
  const paidId = randomUUID();
  await sql.query(paid, [gym, trial, paidId]);
  assert.equal((await sql.query("select revoked from licenses where id=$1", [trial])).rows[0].revoked, true);
  assert.equal((await sql.query("select is_trial from licenses where id=$1", [paidId])).rows[0].is_trial, false);
  pass("paid activation retires trial atomically");
  assert.equal((await sql.query("select id from current_subscriptions where gym_id=$1", [gym])).rows[0].id, paidId);
  assert.equal(Number((await sql.query("select mrr_usd from fleet_mrr")).rows[0].mrr_usd), 199);
  pass("dashboard uses newest entitlement and payment-confirmed revenue");
  await rejects("duplicate stale payment confirmation cannot issue twice", paid, [gym, trial, randomUUID()]);
  await sql.query("insert into gyms(id,name,tier) values($1,'Other tenant','basic')", [otherGym]);
  const member = randomUUID(), attendance = randomUUID();
  await sql.query("insert into members(id,gym_id,full_name) values($1,$2,'Fixture member')", [member, gym]);
  await rejects("cross-tenant member UUID cannot be rebound", "insert into members(id,gym_id,full_name) values($1,$2,'Attack') on conflict(id) do update set gym_id=excluded.gym_id", [member, otherGym]);
  await rejects("attendance cannot reference another facility member", "insert into attendance(id,gym_id,member_id) values($1,$2,$3)", [attendance, otherGym, member]);
  await sql.query("select set_config('request.jwt.claim.sub',$1,false)", [owner]);
  assert.equal((await sql.query("select public.current_role() role")).rows[0].role, "owner");
  await sql.query("update auth.users set raw_app_meta_data='{}' where id=$1", [owner]);
  assert.equal((await sql.query("select public.current_role() role, my_gym_ids() gyms")).rows[0].role, "");
  assert.deepEqual((await sql.query("select my_gym_ids() gyms")).rows[0].gyms, []);
  pass("authorization follows current account metadata, not stale JWT claims");
  await sql.exec("set role authenticated");
  await rejects("browsers cannot read raw license tokens", "select raw_token from licenses");
  await rejects("browsers cannot execute service-role provisioning", provision, [owner, randomUUID(), randomUUID()]);
  await rejects("browsers cannot enable or reassign terminals", "insert into terminals(gym_id,hwid,name,registered_by) values($1,'synthetic-device','Attack',$2)", [gym, owner]);
  await sql.exec("reset role");
  const cashier=randomUUID(),product=randomUUID();
  await sql.query("insert into staff(id,gym_id,full_name,username,pin_hash) values($1,$2,'Fixture cashier','fixture','not-a-real-pin-hash')",[cashier,gym]);
  await sql.query("insert into products(id,gym_id,name,price_cents,stock) values($1,$2,'Fixture Water',100,1000)",[product,gym]);
  await sql.query("update auth.users set raw_app_meta_data=$2 where id=$1",[owner,JSON.stringify({role:"owner",gym_ids:[gym]})]);
  await sql.exec("set role authenticated");
  await rejects("owners cannot read staff PIN hashes","select pin_hash from staff");
  await rejects("dashboard cannot read raw biometric vectors","select face_vector from members");
  await rejects("dashboard cannot rewrite sale contents","update sales set total_cents=1");
  await rejects("dashboard cannot forge attendance","insert into attendance(gym_id) values($1)",[gym]);
  assert.equal((await sql.query("update staff set active=false where id=$1 returning id",[cashier])).rows.length,1);
  pass("owner can deactivate staff without exposing the hash");
  await sql.exec("reset role");
  await sql.query("update auth.users set raw_app_meta_data=$2 where id=$1",[owner,JSON.stringify({role:"manager",gym_ids:[gym]})]);
  await sql.exec("set role authenticated");
  assert.equal((await sql.query("select id from products where id=$1",[product])).rows.length,1);
  assert.equal((await sql.query("update products set price_cents=1 where id=$1 returning id",[product])).rows.length,0);
  assert.equal((await sql.query("update staff set active=true where id=$1 returning id",[cashier])).rows.length,0);
  pass("manager can read inventory but cannot change pricing or credentials");
  await sql.exec("reset role");
  await sql.query("update auth.users set raw_app_meta_data=$2 where id=$1",[owner,JSON.stringify({role:"owner",gym_ids:[gym]})]);
  const items=JSON.stringify([{product_id:product,qty:1,unit_cents:100,discount_cents:40}]);
  await sql.query("insert into sales(gym_id,items,total_cents,pay_method,created_at) select $1,$2::jsonb,60,'cash',now() from generate_series(1,600)",[gym,items]);
  await sql.query("insert into sales(gym_id,items,total_cents,pay_method,status) values($1,$2,60,'cash','refund'),($1,$2,60,'cash','void'),($3,$2,999999,'cash','sale')",[gym,items,otherGym]);
  await sql.exec("set role authenticated");
  const report=(await sql.query("select owner_report() report")).rows[0].report;
  assert.equal(report.today_revenue_cents,35940);
  assert.equal(report.today_transactions,601);
  assert.equal(report.top_products[0].total_cents,35940);
  assert.equal(report.daily.length,30);
  assert.equal(report.branches.length,1);
  pass("complete RLS-scoped report counts over 500 sales with refunds and discounts");
  await sql.exec("reset role");
  await sql.query("update members set status='frozen',expires_at=now()+interval '1 day' where id=$1",[member]);
  await sql.query("select sync_member_enrollment($1,$2,'Changed face',$3::jsonb,now()+interval '30 days')",[gym,member,JSON.stringify(new Array(512).fill(0.1))]);
  assert.equal((await sql.query("select status from members where id=$1",[member])).rows[0].status,"frozen");
  pass("face reupload does not reset frozen lifecycle or membership expiry");
  const ceo=randomUUID();
  await sql.query("insert into auth.users(id,email,email_confirmed_at,raw_app_meta_data) values($1,'ceo@example.invalid',now(),'{\"role\":\"ceo\"}')",[ceo]);
  await rejects("last CEO cannot be removed", "select set_dashboard_access($1,$1,null,'{}')",[ceo]);
  await rejects("unverified account cannot receive dashboard access", "select set_dashboard_access($1,$2,'owner',$3)",[ceo,unverified,[gym]]);
  await rejects("assignment must name an existing facility", "select set_dashboard_access($1,$2,'manager',$3)",[ceo,owner,[randomUUID()]]);
  await sql.query("select set_dashboard_access($1,$2,null,'{}')",[ceo,owner]);
  await rejects("demoted owner cannot restore access through onboarding",provision,[owner,randomUUID(),randomUUID()]);
  await sql.query("select set_dashboard_access($1,$2,'owner',$3)",[ceo,owner,[gym]]);
  await sql.query("insert into auth.mfa_factors(id,user_id,status) values($1,$2,'verified')",[randomUUID(),owner]);
  await sql.exec("set role authenticated");
  assert.equal((await sql.query("select public.current_role() role")).rows[0].role,"");
  assert.equal((await sql.query("select id from gyms")).rows.length,0);
  pass("enrolled MFA blocks direct REST role and facility access at AAL1");
  await sql.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({aal:"aal2"})]);
  assert.equal((await sql.query("select public.current_role() role")).rows[0].role,"owner");
  assert.equal((await sql.query("select id from gyms")).rows.length,1);
  pass("AAL2 restores assigned facility access without stale JWT metadata");
  await rejects("browser cannot execute account administration RPC", "select set_dashboard_access($1,$2,'ceo','{}')",[ceo,owner]);
  console.log(`${tests} database scenarios passed; no production writes`);
} catch (error) {
  console.error("Database scenario failed:", error.message);
  process.exitCode = 1;
} finally { await sql.close(); }
